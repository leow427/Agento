import json
import sys
from pathlib import Path

from art.animations import ANIMATIONS, START
from art.compose import compose
from art.palette import GRID, PALETTE, PALETTE_ORDER

ROOT = Path(__file__).resolve().parent.parent


def build_model():
    frames, index, anims = [], {}, {}
    for name, a in ANIMATIONS.items():
        steps = []
        for s in a["steps"]:
            rows = tuple(compose(s["layers"]))
            if rows not in index:
                index[rows] = len(frames)
                frames.append(rows)
            steps.append({"frame": index[rows], "ms": s["ms"]})
        anims[name] = {
            "steps": steps,
            "loop": a["loop"],
            "hold_ms": a.get("hold_ms", 0),
            "next": a["next"],
        }
    return {"grid": GRID, "frames": [list(f) for f in frames], "anims": anims, "start": START}


def _hex(rgb):
    return None if rgb is None else "#%02x%02x%02x" % rgb


def rgb565(rgb):
    if rgb is None:
        return 0
    r, g, b = rgb
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def write_js(model, path):
    data = dict(model, palette={ch: _hex(rgb) for ch, rgb in PALETTE.items()})
    Path(path).write_text("window.DATA = " + json.dumps(data) + ";\n")


def write_header(model, path):
    names = list(model["anims"])
    enum = ["ANIM_" + n.upper() for n in names]
    pal = ", ".join("0x%04X" % rgb565(PALETTE[c]) for c in PALETTE_ORDER)
    rgb = ", ".join("0x%02X%02X%02X" % (PALETTE[c] or (0, 0, 0)) for c in PALETTE_ORDER)
    out = [
        "// GENERATED by tools/build.py -- do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "constexpr int GRID = %d;" % model["grid"],
        "constexpr int FRAME_COUNT = %d;" % len(model["frames"]),
        "constexpr uint16_t PALETTE565[%d] = {%s};" % (len(PALETTE_ORDER), pal),
        "constexpr uint32_t PALETTE_RGB[%d] = {%s};" % (len(PALETTE_ORDER), rgb),
        "",
        "struct Step { uint16_t frame; uint16_t ms; };",
        "struct Anim { const Step* steps; uint8_t count; bool loop; uint32_t holdMs; uint8_t next; };",
        "",
        "enum AnimId : uint8_t { %s, ANIM_COUNT };" % ", ".join(enum),
        "",
        "const uint8_t FRAMES[FRAME_COUNT][GRID * GRID] = {",
    ]
    for rows in model["frames"]:
        flat = "".join(rows)
        out.append("  {" + ",".join(str(PALETTE_ORDER.index(ch)) for ch in flat) + "},")
    out.append("};")
    out.append("")
    for n in names:
        steps = ", ".join("{%d, %d}" % (s["frame"], s["ms"]) for s in model["anims"][n]["steps"])
        out.append("const Step STEPS_%s[] = {%s};" % (n.upper(), steps))
    out.append("")
    out.append("const Anim ANIMS[ANIM_COUNT] = {")
    for n in names:
        a = model["anims"][n]
        out.append(
            "  {STEPS_%s, %d, %s, %d, ANIM_%s},"
            % (n.upper(), len(a["steps"]), "true" if a["loop"] else "false", a["hold_ms"], a["next"].upper())
        )
    out.append("};")
    out.append("")
    out.append("constexpr uint8_t ANIM_START = ANIM_%s;" % model["start"].upper())
    Path(path).write_text("\n".join(out) + "\n")


def main():
    model = build_model()
    write_js(model, ROOT / "preview" / "data.js")
    write_header(model, ROOT / "firmware" / "lib" / "buddy" / "frames_data.h")
    print("built %d frames, %d anims" % (len(model["frames"]), len(model["anims"])))


if __name__ == "__main__":
    sys.exit(main())
